import {
  Banknote,
  BookOpen,
  Briefcase,
  Building2,
  Calendar,
  Code,
  Cpu,
  FileText,
  FlaskConical,
  Globe,
  GraduationCap,
  Heart,
  Landmark,
  Leaf,
  Megaphone,
  Palette,
  Scale,
  Settings,
  Shield,
  Tag,
  Users,
  Wallet,
  type LucideIcon,
} from "lucide-react";

/** Lucide names (and the preview's short names) a domain topic may store in `Topic.icon`. */
const ICONS: Readonly<Record<string, LucideIcon>> = {
  banknote: Banknote,
  book: BookOpen,
  "book-open": BookOpen,
  briefcase: Briefcase,
  building: Building2,
  "building-2": Building2,
  calendar: Calendar,
  code: Code,
  cpu: Cpu,
  "file-text": FileText,
  flask: FlaskConical,
  "flask-conical": FlaskConical,
  globe: Globe,
  graduation: GraduationCap,
  "graduation-cap": GraduationCap,
  heart: Heart,
  landmark: Landmark,
  leaf: Leaf,
  megaphone: Megaphone,
  palette: Palette,
  scale: Scale,
  settings: Settings,
  shield: Shield,
  tag: Tag,
  users: Users,
  wallet: Wallet,
};

/** The icon for a topic's stored icon name; a tag when it has none or names one we don't draw. */
export const topicIcon = (name: string | undefined): LucideIcon => (name && ICONS[name]) || Tag;
